rd_check <- function(text) {
  file <- tempfile(fileext = ".Rd")
  on.exit(unlink(file), add = TRUE)
  writeLines(text, file)
  rd <- tools::parse_Rd(file)
  tools::checkRd(rd)
}

test_that("a help page is written from the Zig doc comment", {
  item <- list(
    name = "scale_by", parameters = c("x", "factor"), internal = FALSE,
    doc = paste(
      "Scale a vector.", "", "Multiplies every element by `factor`; 100% of the values change.",
      "@param x A numeric vector.", "@param factor A number,", "  applied to every element.",
      "@return A numeric vector of the same length.", "@details Uses {braces} and a back\\slash.",
      "@examples", "scale_by(c(1, 2), 10)", "x <- c(a = 1) # 10%", sep = "\n"
    )
  )
  page <- rzig:::.rzig_render_rd(item)
  expect_match(page, "\\name{scale_by}", fixed = TRUE)
  expect_match(page, "\\title{Scale a vector}", fixed = TRUE)
  expect_match(page, "\\code{factor}; 100\\% of the values change.", fixed = TRUE)
  expect_match(page, "\\item{factor}{A number, applied to every element.}", fixed = TRUE)
  expect_match(page, "\\value{\nA numeric vector of the same length.\n}", fixed = TRUE)
  expect_match(page, "Uses \\{braces\\} and a back\\\\slash.", fixed = TRUE)
  expect_match(page, "\\examples{\nscale_by(c(1, 2), 10)\nx <- c(a = 1) # 10\\%\n}", fixed = TRUE)
  expect_length(rd_check(page), 0L)
  bare <- rzig:::.rzig_render_rd(list(name = "bare", parameters = "x", internal = FALSE, doc = ""))
  expect_match(bare, "\\title{Call bare in Zig}", fixed = TRUE)
  expect_match(bare, "\\item{x}{A value passed to the Zig implementation.}", fixed = TRUE)
  expect_length(rd_check(bare), 0L)
})

test_that("document writes, refreshes and removes rzig's help pages only", {
  path <- local_package("rdpkg")
  suppressMessages(use_rzig(path))
  page <- file.path(path, "man", "hello_zig.Rd")
  expect_true(file.exists(page))
  expect_identical(readLines(page, n = 1L), "% Generated by rzig::document(): do not edit by hand")
  expect_true(any(grepl('hello_zig("R")', readLines(page), fixed = TRUE)))
  expect_true(rzig_status(path)$ok[rzig_status(path)$step == "Bindings"])
  main <- file.path(path, "src", "rzig", "src", "main.zig")
  writeLines(sub("Return a friendly greeting.", "Return a warm greeting.", readLines(main), fixed = TRUE), main)
  status <- rzig_status(path)
  expect_match(status$detail[status$step == "Bindings"], "man/hello_zig.Rd", fixed = TRUE)
  suppressMessages(document(path))
  expect_true(any(grepl("\\title{Return a warm greeting}", readLines(page), fixed = TRUE)))
  writeLines(c("\\name{mine}", "\\alias{mine}", "\\title{Mine}", "\\description{Mine.}"),
    file.path(path, "man", "mine.Rd"))
  writeLines(sub("pub fn hello_zig", "pub fn greet_zig", readLines(main), fixed = TRUE), main)
  expect_message(document(path), "Generated RZig bindings")
  expect_false(file.exists(page))
  expect_true(file.exists(file.path(path, "man", "greet_zig.Rd")))
  expect_true(file.exists(file.path(path, "man", "mine.Rd")))
  writeLines(c("\\name{greet_zig}", "\\alias{greet_zig}", "\\title{Mine}", "\\description{Mine.}"),
    file.path(path, "man", "greet_zig.Rd"))
  expect_message(document(path), "not written by rzig")
  expect_identical(readLines(file.path(path, "man", "greet_zig.Rd"), n = 1L), "\\name{greet_zig}")
})

test_that("internal routines get no help page and roxygen packages get none from rzig", {
  path <- local_package("rdinternal")
  suppressMessages(use_rzig(path))
  main <- file.path(path, "src", "rzig", "src", "main.zig")
  writeLines(sub("/// @export", "/// @export internal", readLines(main), fixed = TRUE), main)
  suppressMessages(document(path))
  expect_false(file.exists(file.path(path, "man", "hello_zig.Rd")))
  rox <- local_package("rdroxygen")
  writeLines("# Generated by roxygen2: do not edit by hand", file.path(rox, "NAMESPACE"))
  suppressMessages(use_rzig(rox))
  expect_false(file.exists(file.path(rox, "man", "hello_zig.Rd")))
})
