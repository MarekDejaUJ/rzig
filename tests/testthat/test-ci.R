test_that("use_rzig_ci writes a workflow with the requested matrix", {
  path <- local_package("cipkg")
  suppressMessages(use_rzig(path))
  file <- suppressMessages(use_rzig_ci(path))
  expect_identical(normalizePath(file), normalizePath(file.path(path, ".github", "workflows", "rzig-check.yaml")))
  text <- readLines(file)
  expect_true("        os: [ubuntu-latest, macos-latest, windows-latest]" %in% text)
  expect_true("        zig: [\"0.16.0\", \"0.17.0\"]" %in% text)
  expect_false(any(grepl("@OS@|@ZIG@", text)))
  expect_identical(sum(readLines(file.path(path, ".Rbuildignore")) == "^\\.github$"), 1L)
  expect_error(use_rzig_ci(path), "overwrite = TRUE", fixed = TRUE)
  suppressMessages(use_rzig_ci(path, zig = "0.16.0", os = "ubuntu-latest", overwrite = TRUE))
  text <- readLines(file)
  expect_true("        os: [ubuntu-latest]" %in% text)
  expect_true("        zig: [\"0.16.0\"]" %in% text)
  expect_identical(sum(readLines(file.path(path, ".Rbuildignore")) == "^\\.github$"), 1L)
  skip_if_not_installed("yaml")
  workflow <- yaml::read_yaml(file)
  expect_identical(workflow$jobs$`R-CMD-check`$strategy$matrix$zig, "0.16.0")
  expect_identical(length(workflow$jobs$`R-CMD-check`$steps), 6L)
})

test_that("use_rzig_ci rejects unsupported Zig versions and runner names", {
  path <- local_package("cibad")
  suppressMessages(use_rzig(path))
  expect_error(use_rzig_ci(path, zig = "0.15.2"), "Zig releases of the series")
  expect_error(use_rzig_ci(path, zig = "0.17.0-dev.12+abc"), "Zig releases of the series")
  expect_error(use_rzig_ci(path, os = "ubuntu latest"), "GitHub runners")
  bare <- local_package("cibare")
  expect_error(use_rzig_ci(bare), "run use_rzig(path) first", fixed = TRUE)
})
