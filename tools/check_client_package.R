# CRAN-style check of a newly generated client package (CI job client-check).
#
# Creates a package with use_rzig() in a temporary directory, builds it, and
# runs R CMD check --as-cran with the settings CRAN uses for submissions that
# matter for compiled code: two cores, the CPU-to-elapsed threshold for the
# installation, and a separate temporary directory whose detritus is reported.
# Fails on any ERROR, WARNING or NOTE.
#
# Usage: Rscript tools/check_client_package.R
# Needs rzig installed and a supported Zig compiler (ZIG or PATH).

stopifnot(requireNamespace("rzig", quietly = TRUE))
compiler <- rzig::find_zig()
work <- tempfile("rzig-client-check-")
dir.create(work)
package <- file.path(work, "clientpkg")
dir.create(package)
writeLines(c(
  "Package: clientpkg",
  "Version: 0.0.1",
  "Title: A Client Package Generated by 'rzig'",
  "Description: Calls a function written in 'Zig' through the native boundary",
  "    that 'rzig' generates; used to check generated packages.",
  "License: GPL-3",
  "Authors@R: person(\"A\", \"Author\", email = \"a@example.org\", role = c(\"aut\", \"cre\"))",
  "Encoding: UTF-8",
  paste("SystemRequirements: Zig", rzig:::.rzig_zig_series_label())
), file.path(package, "DESCRIPTION"))
rzig::use_rzig(package)
status <- rzig::rzig_status(package)
print(status)
stopifnot(all(status$ok))

old <- setwd(work)
on.exit(setwd(old), add = TRUE)
r <- file.path(R.home("bin"), "R")
build <- system2(r, c("CMD", "build", "clientpkg"), stdout = TRUE, stderr = TRUE)
cat(build, sep = "\n")
stopifnot(is.null(attr(build, "status")))
tarball <- list.files(work, pattern = "^clientpkg_.*\\.tar\\.gz$")
check_tmp <- file.path(work, "check-tmp")
dir.create(check_tmp)
environment <- c(
  paste0("ZIG=", compiler$path),
  paste0("TMPDIR=", check_tmp),
  "_R_CHECK_CRAN_INCOMING_=false",
  "_R_CHECK_CRAN_INCOMING_REMOTE_=false",
  "_R_CHECK_LIMIT_CORES_=TRUE",
  "_R_CHECK_INSTALL_TIMING_CPU_TO_ELAPSED_THRESHOLD_=2.5",
  "_R_CHECK_THINGS_IN_TEMP_DIR_=true",
  "_R_CHECK_FORCE_SUGGESTS_=false",
  # Environment checks unrelated to compiled code (network time, HTML Tidy).
  "_R_CHECK_FUTURE_FILE_TIMESTAMPS_=false",
  "_R_CHECK_RD_VALIDATE_RD2HTML_=false"
)
check <- system2(r, c("CMD", "check", "--as-cran", "--no-manual", tarball),
  stdout = TRUE, stderr = TRUE, env = environment)
log <- readLines(file.path(work, "clientpkg.Rcheck", "00check.log"))
cat(log, sep = "\n")
flagged <- grep("\\.\\.\\. (NOTE|WARNING|ERROR)", log, value = TRUE)
status_line <- grep("^Status:", log, value = TRUE)
if (length(flagged) || !identical(status_line, "Status: OK")) {
  stop("the generated client package did not pass R CMD check cleanly: ",
    paste(c(flagged, status_line), collapse = "; "), call. = FALSE)
}
leftovers <- list.files(check_tmp, all.files = TRUE, no.. = TRUE)
leftovers <- leftovers[!grepl("^Rtmp", leftovers)]
if (length(leftovers)) {
  stop("files left in the temporary directory: ", paste(leftovers, collapse = ", "), call. = FALSE)
}
cat("generated client package: R CMD check --as-cran Status OK\n")
