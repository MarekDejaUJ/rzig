# Regenerate R/known-templates.R: the MD5 sums of every version of the build
# templates and Zig build files that rzig has shipped in its git history.
# update_rzig() replaces a file in a client package only when it is identical
# to one of these versions (an unmodified template of an older rzig); any
# other content is a customization and is kept.
#
# Run from the repository root before each release:
#   Rscript tools/known_template_hashes.R

templates <- c(
  "configure" = "inst/templates/configure",
  "configure.win" = "inst/templates/configure.win",
  "cleanup" = "inst/templates/cleanup",
  "cleanup.win" = "inst/templates/cleanup.win",
  "Makevars" = "inst/templates/Makevars",
  "Makevars.win" = "inst/templates/Makevars.win",
  "entry.c" = "inst/templates/entry.c",
  "build.zig" = "inst/zig/build.zig",
  "build.zig.zon" = "inst/zig/build.zig.zon",
  "tools/repack_macos_archive.sh" = "inst/zig/tools/repack_macos_archive.sh",
  "tools/fetch_zig.R" = "inst/zig/tools/fetch_zig.R",
  "tools/imports.R" = "inst/zig/tools/imports.R",
  "tools/scan.zig" = "inst/zig/tools/scan.zig"
)

normalize <- function(text) {
  text <- gsub("\r\n", "\n", text, fixed = TRUE)
  paste0(sub("\n+$", "", text), "\n")
}

text_md5 <- function(text) {
  file <- tempfile()
  on.exit(unlink(file))
  writeBin(charToRaw(normalize(text)), file)
  unname(tools::md5sum(file))
}

git <- function(...) {
  out <- suppressWarnings(system2("git", c(...), stdout = TRUE, stderr = FALSE))
  if (!is.null(attr(out, "status"))) character() else out
}

hashes <- lapply(templates, function(path) {
  commits <- git("log", "--all", "--format=%H", "--", path)
  values <- character()
  for (commit in commits) {
    content <- git("show", paste0(commit, ":", path))
    if (length(content)) values <- c(values, text_md5(paste(content, collapse = "\n")))
  }
  if (file.exists(path)) {
    values <- c(values, text_md5(readChar(path, file.info(path)$size, useBytes = TRUE)))
  }
  sort(unique(values))
})

lines <- c(
  "# Generated by tools/known_template_hashes.R - do not edit.",
  "# MD5 sums (of the text with LF line endings and one final newline) of every",
  "# version of the build templates in the history of rzig. entry.c is hashed",
  "# with its @PKG@ placeholder.",
  ".rzig_known_template_hashes <- list("
)
entries <- vapply(names(hashes), function(name) {
  sprintf("  \"%s\" = c(\n%s\n  )", name, paste0("    \"", hashes[[name]], "\"", collapse = ",\n"))
}, character(1L))
lines <- c(lines, paste0(entries, c(rep(",", length(entries) - 1L), "")), ")")
writeLines(lines, "R/known-templates.R")
cat(sprintf("%-32s %d versions\n", names(hashes), lengths(hashes)), sep = "")
