.rzig_system2 <- function(
  command,
  arguments,
  action,
  environment = character()
) {
  output <- tryCatch(
    suppressWarnings(system2(
      command,
      arguments,
      stdout = TRUE,
      stderr = TRUE,
      env = environment
    )),
    error = function(error) {
      stop(
        "failed to ", action, ": ", conditionMessage(error),
        call. = FALSE
      )
    }
  )
  status <- attr(output, "status", exact = TRUE)
  if (is.null(status)) {
    status <- 0L
  }
  if (!identical(as.integer(status), 0L)) {
    details <- paste(output, collapse = "\n")
    if (nzchar(details)) {
      details <- paste0(":\n", details)
    }
    stop("failed to ", action, details, call. = FALSE)
  }
  invisible(output)
}

.rzig_merge_namespace <- function(existing, generated, package, old_wrapper) {
  begin <- "# Generated by rzig::document(): begin"
  end <- "# Generated by rzig::document(): end"
  starts <- which(trimws(existing) == begin)
  ends <- which(trimws(existing) == end)
  if (length(starts) != length(ends) || length(starts) > 1L ||
      (length(starts) == 1L && ends < starts)) {
    stop("NAMESPACE contains an incomplete RZig-generated block", call. = FALSE)
  }

  if (length(starts) == 1L) {
    existing <- existing[-seq.int(starts, ends)]
  } else {
    legacy <- sprintf(
      "useDynLib(%s, .registration = TRUE, .fixes = \"C_\")",
      package
    )
    existing <- existing[trimws(existing) != legacy]

    wrapper_matches <- regexec(
      "^([A-Za-z.][A-Za-z0-9._]*)[[:space:]]*<-[[:space:]]*function\\(",
      old_wrapper
    )
    captures <- regmatches(old_wrapper, wrapper_matches)
    old_exports <- vapply(
      captures[lengths(captures) > 1L],
      function(match) match[2L],
      character(1L)
    )
    legacy_exports <- c(
      sprintf("export(%s)", old_exports),
      sprintf("export(\"%s\")", old_exports)
    )
    generated_exports <- generated[grepl("^export\\(", generated)]
    existing <- existing[
      !trimws(existing) %in% unique(c(legacy_exports, generated_exports))
    ]
  }

  while (length(existing) && !nzchar(existing[[length(existing)]])) {
    existing <- existing[-length(existing)]
  }
  if (length(existing)) {
    c(existing, "", generated)
  } else {
    generated
  }
}

.rzig_replace_file <- function(source, destination) {
  dir.create(dirname(destination), recursive = TRUE, showWarnings = FALSE)
  if (!file.copy(source, destination, overwrite = TRUE, copy.mode = TRUE)) {
    stop("failed to update generated file: ", destination, call. = FALSE)
  }
  invisible(destination)
}

.rzig_write_text <- function(text, destination) {
  generated <- tempfile("rzig-generated-")
  on.exit(unlink(generated), add = TRUE)
  connection <- file(generated, open = "wb")
  writeBin(charToRaw(text), connection)
  close(connection)
  .rzig_replace_file(generated, destination)
}

.rzig_normalize_newlines <- function(text) {
  if (is.null(text)) return(NULL)
  out <- gsub("\r\n", "\n", text, fixed = TRUE, useBytes = TRUE)
  Encoding(out) <- "unknown"
  out
}

.rzig_read_text <- function(path) {
  if (!file.exists(path)) {
    return(NULL)
  }
  size <- file.info(path)$size
  if (is.na(size) || size == 0) {
    return("")
  }
  text <- readChar(path, size, useBytes = TRUE)
  Encoding(text) <- "unknown"
  text
}

.rzig_copy_tree <- function(source, destination, skip = NULL) {
  files <- list.files(
    source,
    all.files = TRUE,
    full.names = TRUE,
    recursive = TRUE,
    include.dirs = FALSE,
    no.. = TRUE
  )
  prefix_length <- nchar(source) + 2L
  relative <- substring(files, prefix_length)
  if (!is.null(skip)) {
    keep <- !grepl(skip, relative)
    files <- files[keep]
    relative <- relative[keep]
  }
  for (index in seq_along(files)) {
    target <- file.path(destination, relative[index])
    dir.create(dirname(target), recursive = TRUE, showWarnings = FALSE)
    if (!file.copy(files[index], target, overwrite = TRUE, copy.mode = TRUE)) {
      stop("failed to copy RZig asset: ", relative[index], call. = FALSE)
    }
  }
  invisible(destination)
}

# Files pkgbuild (and so devtools::load_all()) should treat as sources of the
# shared object; it otherwise watches only C, C++, Fortran and Rust files.
.rzig_extra_sources <- c(
  "src/rzig/src", "src/rzig/framework", "src/rzig/build.zig", "src/rzig/build.zig.zon"
)

.rzig_extra_sources_field <- "Config/build/extra-sources"

# The entries of a comma-separated DESCRIPTION field, or character() when the
# field is absent. Continuation lines (starting with white space) belong to
# the field.
.rzig_description_field <- function(lines, field) {
  start <- which(startsWith(lines, paste0(field, ":")))
  if (!length(start)) return(list(start = NA_integer_, end = NA_integer_, entries = character()))
  start <- start[[1L]]
  end <- start
  while (end < length(lines) && grepl("^[ \t]", lines[[end + 1L]])) end <- end + 1L
  value <- paste(c(substring(lines[[start]], nchar(field) + 2L), lines[seq_len(end - start) + start]), collapse = " ")
  entries <- trimws(strsplit(value, ",", fixed = TRUE)[[1L]])
  list(start = start, end = end, entries = entries[nzchar(entries)])
}

# Add the Zig sources to Config/build/extra-sources, keeping entries the
# package author listed. Returns TRUE when DESCRIPTION changed.
.rzig_add_extra_sources <- function(path) {
  file <- file.path(path, "DESCRIPTION")
  lines <- strsplit(.rzig_normalize_newlines(.rzig_read_text(file)), "\n", fixed = TRUE)[[1L]]
  field <- .rzig_description_field(lines, .rzig_extra_sources_field)
  missing <- setdiff(.rzig_extra_sources, field$entries)
  if (!length(missing)) return(FALSE)
  line <- paste0(.rzig_extra_sources_field, ": ", paste(c(field$entries, missing), collapse = ", "))
  if (is.na(field$start)) {
    lines <- c(lines, line)
  } else {
    lines <- c(lines[seq_len(field$start - 1L)], line, lines[seq.int(field$end + 1L, length.out = length(lines) - field$end)])
  }
  .rzig_write_text(paste0(paste(lines, collapse = "\n"), "\n"), file)
  TRUE
}

.rzig_buildignore_entries <- c(
  "^src/rzig/\\.zig-cache$",
  "^src/rzig/\\.zig-global-cache$",
  "^src/rzig/zig-out$"
)

.rzig_add_buildignore <- function(path) {
  file <- file.path(path, ".Rbuildignore")
  existing <- if (file.exists(file)) readLines(file, warn = FALSE) else character()
  missing <- setdiff(.rzig_buildignore_entries, existing)
  if (length(missing)) writeLines(c(existing, missing), file)
  invisible(file)
}
