# Help pages for exported Zig functions in packages that do not use roxygen2.
# In roxygen-managed packages roxygen2 writes the pages from the blocks of
# R/rzig-wrappers.R instead.

.rzig_rd_header <- "% Generated by rzig::document(): do not edit by hand"

.rzig_rd_sections <- c(
  "@details" = "details", "@seealso" = "seealso", "@references" = "references",
  "@note" = "note"
)

# Split a doc comment into the leading text and the tagged sections.
.rzig_parse_doc <- function(doc) {
  lines <- .rzig_doc_lines(doc)
  parsed <- list(text = character(), params = list(), sections = list())
  current <- NULL
  for (line in lines) {
    trimmed <- trimws(line, whitespace = "[ \t\r]")
    tag <- regmatches(trimmed, regexpr("^@[A-Za-z]+", trimmed))
    if (length(tag)) {
      rest <- trimws(substring(trimmed, nchar(tag) + 1L))
      if (identical(tag, "@param")) {
        name <- sub("^`?([^`[:space:]]+)`?.*$", "\\1", rest)
        description <- trimws(sub("^`?[^`[:space:]]+`?", "", rest))
        parsed$params[[name]] <- description
        current <- list(kind = "param", name = name)
      } else if (tag %in% c("@return", "@returns")) {
        parsed$sections$value <- rest
        current <- list(kind = "section", name = "value")
      } else if (identical(tag, "@examples")) {
        parsed$sections$examples <- if (nzchar(rest)) rest else character()
        current <- list(kind = "examples")
      } else if (tag %in% names(.rzig_rd_sections)) {
        section <- .rzig_rd_sections[[tag]]
        parsed$sections[[section]] <- rest
        current <- list(kind = "section", name = section)
      } else {
        current <- list(kind = "ignored")
      }
      next
    }
    if (is.null(current)) {
      parsed$text <- c(parsed$text, line)
    } else if (identical(current$kind, "param")) {
      parsed$params[[current$name]] <- paste(parsed$params[[current$name]], trimmed)
    } else if (identical(current$kind, "section")) {
      parsed$sections[[current$name]] <- paste(parsed$sections[[current$name]], trimmed, sep = "\n")
    } else if (identical(current$kind, "examples")) {
      parsed$sections$examples <- c(parsed$sections$examples, line)
    }
  }
  parsed
}

# Escape text for an Rd text section; `code` spans become \code{}.
.rzig_rd_text <- function(text) {
  text <- trimws(text)
  pieces <- strsplit(text, "`", fixed = TRUE)[[1L]]
  if (!length(pieces)) return("")
  escape <- function(x) {
    x <- gsub("\\", "\\\\", x, fixed = TRUE)
    x <- gsub("%", "\\%", x, fixed = TRUE)
    x <- gsub("{", "\\{", x, fixed = TRUE)
    gsub("}", "\\}", x, fixed = TRUE)
  }
  out <- character()
  for (index in seq_along(pieces)) {
    piece <- escape(pieces[[index]])
    out <- c(out, if (index %% 2L == 0L) paste0("\\code{", piece, "}") else piece)
  }
  paste(out, collapse = "")
}

.rzig_rd_examples <- function(lines) {
  lines <- gsub("\\", "\\\\", lines, fixed = TRUE)
  gsub("%", "\\%", lines, fixed = TRUE)
}

.rzig_render_rd <- function(item) {
  parsed <- .rzig_parse_doc(item$doc)
  paragraphs <- strsplit(trimws(paste(parsed$text, collapse = "\n")), "\n[[:space:]]*\n")[[1L]]
  paragraphs <- paragraphs[nzchar(trimws(paragraphs))]
  title <- if (length(paragraphs)) {
    sub("\\.$", "", trimws(gsub("[[:space:]]*\n[[:space:]]*", " ", paragraphs[[1L]])))
  } else {
    paste("Call", item$name, "in Zig")
  }
  description <- if (length(paragraphs)) paragraphs else paste0(title, ".")
  usage <- paste0(.rzig_r_identifier(item$name), "(", .rzig_formals_text(item), ")")
  arguments <- vapply(item$parameters, function(parameter) {
    text <- parsed$params[[parameter]]
    if (is.null(text) || !nzchar(trimws(text))) text <- "A value passed to the Zig implementation."
    sprintf("\\item{%s}{%s}", .rzig_rd_text(parameter), .rzig_rd_text(text))
  }, character(1L))
  value <- parsed$sections$value %||% "The value returned by the Zig implementation."
  lines <- c(
    .rzig_rd_header,
    sprintf("\\name{%s}", .rzig_rd_text(item$name)),
    sprintf("\\alias{%s}", .rzig_rd_text(item$name)),
    sprintf("\\title{%s}", .rzig_rd_text(title)),
    "\\usage{", usage, "}",
    if (length(arguments)) c("\\arguments{", arguments, "}"),
    "\\value{", .rzig_rd_text(value), "}",
    "\\description{", paste(vapply(description, .rzig_rd_text, character(1L)), collapse = "\n\n"), "}"
  )
  for (section in c("details", "note", "seealso", "references")) {
    if (!is.null(parsed$sections[[section]])) {
      lines <- c(lines, sprintf("\\%s{", section), .rzig_rd_text(parsed$sections[[section]]), "}")
    }
  }
  examples <- parsed$sections$examples
  if (length(examples) && any(nzchar(trimws(examples)))) {
    lines <- c(lines, "\\examples{", .rzig_rd_examples(examples), "}")
  }
  paste0(paste(lines, collapse = "\n"), "\n")
}

.rzig_rd_file <- function(name) {
  paste0(gsub("[^A-Za-z0-9._-]", "_", name), ".Rd")
}

.rzig_rd_generated <- function(file) {
  identical(readLines(file, n = 1L, warn = FALSE), .rzig_rd_header)
}

# The help pages document() writes: a named list, file name to text.
.rzig_rd_pages <- function(exports) {
  exported <- Filter(function(item) !.rzig_is_internal(item), exports)
  pages <- lapply(exported, .rzig_render_rd)
  names(pages) <- vapply(exported, function(item) .rzig_rd_file(item$name), character(1L))
  pages
}

# Write the pages, remove pages rzig wrote for functions that are gone, and
# leave pages of other origin alone. Returns the files written and kept.
.rzig_write_rd <- function(path, exports, roxygen) {
  man <- file.path(path, "man")
  existing <- if (dir.exists(man)) list.files(man, pattern = "\\.Rd$", full.names = TRUE) else character()
  ours <- existing[vapply(existing, .rzig_rd_generated, logical(1L))]
  if (roxygen) {
    # roxygen2 writes the pages of these packages and does not overwrite files
    # it did not generate.
    unlink(ours)
    return(list(written = character(), foreign = character()))
  }
  pages <- .rzig_rd_pages(exports)
  unlink(setdiff(ours, file.path(man, names(pages))))
  written <- character()
  foreign <- character()
  for (file in names(pages)) {
    target <- file.path(man, file)
    if (file.exists(target) && !.rzig_rd_generated(target)) {
      foreign <- c(foreign, file.path("man", file))
      next
    }
    dir.create(man, showWarnings = FALSE)
    .rzig_write_text(pages[[file]], target)
    written <- c(written, file.path("man", file))
  }
  list(written = written, foreign = foreign)
}
