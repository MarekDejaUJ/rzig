#' Render the generated bindings for a set of exported functions
#'
#' Produces the three texts that [document()] writes into a package, without
#' writing anything: the Zig manifest that registers the exported functions,
#' the R wrappers that call them, and the `NAMESPACE` block that resolves the
#' native symbols. Use the function to inspect what [document()] will
#' generate.
#'
#' @param exports An object returned by [scan_exports()].
#' @param package The package name; by default taken from `exports`.
#' @param roxygen Render for a package whose `NAMESPACE` roxygen2 generates:
#'   the wrappers then carry the `useDynLib` directive as a `@rawNamespace`
#'   tag, and `namespace` holds the lines roxygen2 writes for them.
#'
#' @return An object of class `rzig_bindings`: a list with the character
#'   strings `manifest` (`src/rzig/framework/generated/manifest.zig`),
#'   `wrappers` (`R/rzig-wrappers.R`) and `namespace` (the generated
#'   `NAMESPACE` block, or with `roxygen = TRUE` the `NAMESPACE` lines that
#'   roxygen2 writes for the wrappers), and the `exports` the texts were
#'   rendered from.
#' @examples
#' package_path <- tempfile("rzig-render-", tmpdir = tempdir())
#' dir.create(package_path)
#' writeLines(c("Package: examplepkg", "Version: 0.0.1"),
#'   file.path(package_path, "DESCRIPTION"))
#' use_rzig(package_path)
#' bindings <- render_bindings(scan_exports(package_path))
#' cat(bindings$wrappers)
#' cat(bindings$namespace)
#' unlink(package_path, recursive = TRUE)
#' @export
render_bindings <- function(exports, package = attr(exports, "package", exact = TRUE), roxygen = FALSE) {
  if (!inherits(exports, "rzig_exports")) {
    stop("`exports` must be the result of scan_exports()", call. = FALSE)
  }
  if (is.null(package) || length(package) != 1L || !grepl("^[A-Za-z][A-Za-z0-9.]*$", package)) {
    stop("`package` must be a valid R package name", call. = FALSE)
  }
  if (length(roxygen) != 1L || is.na(roxygen)) {
    stop("`roxygen` must be TRUE or FALSE", call. = FALSE)
  }
  roxygen <- isTRUE(roxygen)
  aliases <- .rzig_native_aliases(exports)
  dynlib <- .rzig_use_dynlib_line(exports, aliases, package)
  result <- list(
    manifest = .rzig_render_manifest(exports, package),
    wrappers = .rzig_render_wrappers(exports, aliases, if (roxygen) dynlib),
    namespace = if (roxygen) {
      .rzig_render_roxygen_namespace(exports, dynlib)
    } else {
      .rzig_render_namespace(exports, aliases, package)
    },
    exports = exports
  )
  structure(result, class = "rzig_bindings", package = package, roxygen = roxygen)
}

# The useDynLib directive binding every native symbol object to its routine.
.rzig_use_dynlib_line <- function(exports, aliases, package) {
  entries <- vapply(seq_along(exports), function(index) {
    paste0(aliases[[index]], " = ", .rzig_r_string(exports[[index]]$name))
  }, character(1L))
  paste0("useDynLib(", paste(c(.rzig_r_string(package), entries), collapse = ", "), ")")
}

# NAMESPACE lines as roxygen2 writes them for the generated wrappers.
.rzig_roxygen_export_line <- function(name) {
  if (.rzig_is_syntactic(name) && !name %in% .rzig_reserved_words) {
    paste0("export(", name, ")")
  } else {
    paste0("export(", .rzig_r_string(name), ")")
  }
}

.rzig_render_roxygen_namespace <- function(exports, dynlib) {
  exported <- Filter(function(item) !.rzig_is_internal(item), exports)
  lines <- c(dynlib, vapply(exported, function(item) .rzig_roxygen_export_line(item$name), character(1L)),
    .rzig_class_namespace_lines(exports, roxygen = TRUE))
  paste0(paste(lines, collapse = "\n"), "\n")
}

#' @export
print.rzig_bindings <- function(x, ...) {
  package <- attr(x, "package", exact = TRUE)
  cat(sprintf(
    "Generated bindings for package %s: %d exported function%s\n",
    package, length(x$exports), if (length(x$exports) == 1L) "" else "s"
  ))
  if (!is.null(x$files)) {
    cat("Files written:\n")
    for (file in x$files) cat("  ", file, "\n", sep = "")
  }
  cat("\n-- R/rzig-wrappers.R --\n")
  cat(x$wrappers)
  cat("\n-- NAMESPACE block --\n")
  cat(x$namespace)
  cat("\n-- src/rzig/framework/generated/manifest.zig --\n")
  cat(x$manifest)
  invisible(x)
}

.rzig_render_manifest <- function(exports, package) {
  header <- paste0(
    "//! GENERATED by tools/scan.zig - do not edit.\n",
    "//! Regenerate with `zig build gen` or `rzig::document()`.\n",
    "\n",
    "/// The R package of the exports (for R_RegisterCCallable).\n",
    "pub const package = ", .rzig_zig_string(package), ";\n",
    "\n",
    "/// Bind exported function names to the package's root Zig module.\n",
    "pub fn Bind(comptime root: type) type {\n",
    "    return struct {\n",
    "        const bound_root = root;\n",
    "\n",
    "        /// Metadata for public functions exposed through RZig.\n"
  )
  if (!length(exports)) {
    return(paste0(header, "        pub const exports = .{};\n    };\n}\n"))
  }
  if (any(vapply(exports, function(item) !is.null(item$class), logical(1L)))) {
    header <- sub("/// Bind", "const rzig_class = @import(\"../class.zig\");\n\n/// Bind", header, fixed = TRUE)
  }
  entries <- vapply(exports, function(item) {
    quoted <- vapply(item$parameters, .rzig_zig_string, character(1L))
    list_text <- if (length(quoted) == 0L) {
      ".{}"
    } else if (length(quoted) == 1L) {
      paste0(".{", quoted, "}")
    } else {
      paste0(".{ ", paste(quoted, collapse = ", "), " }")
    }
    paste0(
      "            .{\n",
      "                .name = ", .rzig_zig_string(item$name), ",\n",
      "                .func = ", .rzig_manifest_function(item), ",\n",
      "                .doc = ", .rzig_zig_string(item$doc), ",\n",
      "                .parameters = ", list_text, ",\n",
      "            },\n"
    )
  }, character(1L))
  paste0(
    header,
    "        pub const exports = .{\n",
    paste(entries, collapse = ""),
    "        };\n",
    "    };\n",
    "}\n"
  )
}

# The Zig expression of the function a manifest entry registers.
.rzig_manifest_function <- function(item) {
  role <- item$class$role
  if (is.null(role)) return(paste0("bound_root.", item$identifier))
  if (identical(role, "constructor")) {
    return(paste0("rzig_class.Constructor(bound_root.", item$identifier, ").call"))
  }
  paste0("rzig_class.Method(bound_root.", item$identifier, ", ", .rzig_zig_string(item$class$member), ").call")
}

.rzig_zig_string <- function(value) {
  bytes <- charToRaw(value)
  pieces <- vapply(as.integer(bytes), function(byte) {
    if (byte == 0x22L) return("\\\"")
    if (byte == 0x5cL) return("\\\\")
    if (byte == 0x0aL) return("\\n")
    if (byte == 0x0dL) return("\\r")
    if (byte == 0x09L) return("\\t")
    if (byte >= 0x20L && byte <= 0x7eL) return(rawToChar(as.raw(byte)))
    sprintf("\\x%02x", byte)
  }, character(1L))
  paste0("\"", paste(pieces, collapse = ""), "\"")
}

.rzig_r_string <- function(value) {
  bytes <- as.integer(charToRaw(value))
  unsupported <- bytes %in% c(0:8, 11L, 12L, 14:31, 127L)
  if (any(unsupported)) {
    stop("a generated R string contains a control character", call. = FALSE)
  }
  pieces <- vapply(bytes, function(byte) {
    if (byte == 0x22L) return("\\\"")
    if (byte == 0x5cL) return("\\\\")
    if (byte == 0x0aL) return("\\n")
    if (byte == 0x0dL) return("\\r")
    if (byte == 0x09L) return("\\t")
    rawToChar(as.raw(byte))
  }, character(1L))
  out <- paste0("\"", paste(pieces, collapse = ""), "\"")
  Encoding(out) <- "unknown"
  out
}

.rzig_reserved_words <- c(
  "if", "else", "repeat", "while", "function", "for", "in", "next", "break",
  "TRUE", "FALSE", "NULL", "Inf", "NaN", "NA", "NA_integer_", "NA_real_",
  "NA_complex_", "NA_character_"
)

.rzig_is_syntactic <- function(name) {
  nzchar(name) &&
    grepl("^([A-Za-z]|\\.(?![0-9]))[A-Za-z0-9._]*$", name, perl = TRUE, useBytes = TRUE)
}

.rzig_r_identifier <- function(name) {
  if (.rzig_is_syntactic(name) && !name %in% .rzig_reserved_words) {
    return(name)
  }
  escaped <- gsub("([\\\\`])", "\\\\\\1", name, perl = TRUE, useBytes = TRUE)
  paste0("`", escaped, "`")
}

.rzig_native_aliases <- function(exports) {
  names <- vapply(exports, function(item) item$name, character(1L))
  vapply(seq_along(exports), function(index) {
    preferred <- paste0(names[[index]], "_")
    if (.rzig_is_syntactic(preferred) && !preferred %in% names) {
      return(preferred)
    }
    ordinal <- index
    repeat {
      fallback <- sprintf(".rzig_symbol_%d", ordinal)
      if (!fallback %in% names) return(fallback)
      ordinal <- ordinal + length(exports) + 1L
    }
  }, character(1L))
}

.rzig_render_wrappers <- function(exports, aliases, dynlib = NULL) {
  out <- "# Generated by rzig::document(). Do not edit.\n"
  if (!is.null(dynlib)) {
    # roxygen2 regenerates NAMESPACE from tags; this tag keeps the native
    # symbols in it.
    out <- paste0(out, "\n#' @rawNamespace ", dynlib, "\nNULL\n")
  }
  for (index in seq_along(exports)) {
    item <- exports[[index]]
    arguments <- vapply(item$parameters, .rzig_r_identifier, character(1L))
    call <- paste0(
      ".Call(", aliases[[index]],
      paste0(vapply(arguments, function(argument) paste0(", ", argument), character(1L)), collapse = ""),
      ")"
    )
    if (isTRUE(item$invisible)) call <- paste0("invisible(", call, ")")
    out <- paste0(
      out, "\n",
      .rzig_roxygen_block(item),
      .rzig_r_identifier(item$name), " <- function(", .rzig_formals_text(item),
      ") {\n  ", call, "\n}\n"
    )
  }
  for (item in exports) {
    if (identical(item$class$role, "constructor")) out <- paste0(out, .rzig_render_class_methods(item, !is.null(dynlib)))
  }
  out
}

# The S3 methods of a class: `$` returns a method bound to the object,
# `print` lists the methods, and `.DollarNames` completes their names.
.rzig_render_class_methods <- function(item, roxygen) {
  class <- item$class$name
  methods <- item$class$methods
  names <- vapply(methods, function(method) method$name, character(1L))
  routines <- vapply(names, function(name) .rzig_r_identifier(paste0(class, "_", name)), character(1L))
  entries <- if (length(names)) paste0(vapply(names, .rzig_r_string, character(1L)), " = ", routines) else character()
  usage <- vapply(methods, function(method) {
    sprintf("  $%s(%s)\n", method$name, paste(method$parameters, collapse = ", "))
  }, character(1L))
  quoted_names <- if (length(names)) paste(vapply(names, .rzig_r_string, character(1L)), collapse = ", ") else ""
  tag <- function(text) if (roxygen) paste0(text, "#' @noRd\n") else "#' @noRd\n"
  paste0(
    "\n", tag("#' @export\n"),
    "`$.", class, "` <- function(x, name) {\n",
    "  methods <- list(", paste(entries, collapse = ", "), ")\n",
    "  method <- methods[[name]]\n",
    "  if (is.null(method)) {\n",
    "    stop(sprintf(\"a ", class, " has no method `%s`; its methods are: %s\", name,\n",
    "      paste(names(methods), collapse = \", \")), call. = FALSE)\n",
    "  }\n",
    "  function(...) method(x, ...)\n",
    "}\n",
    "\n", tag("#' @export\n"),
    "print.", class, " <- function(x, ...) {\n",
    "  cat(", .rzig_r_string(paste0("<", class, "> with the methods:\n", paste(usage, collapse = ""))), ")\n",
    "  invisible(x)\n",
    "}\n",
    "\n", tag("#' @exportS3Method utils::.DollarNames\n"),
    ".DollarNames.", class, " <- function(x, pattern = \"\") {\n",
    "  grep(pattern, c(", quoted_names, "), value = TRUE)\n",
    "}\n"
  )
}

# NAMESPACE lines that register the S3 methods of each class.
.rzig_class_namespace_lines <- function(exports, roxygen) {
  classes <- unlist(lapply(exports, function(item) {
    if (identical(item$class$role, "constructor")) item$class$name
  }))
  unlist(lapply(classes, function(class) {
    if (roxygen) {
      c(sprintf('S3method("$",%s)', class), sprintf("S3method(print,%s)", class),
        sprintf("S3method(utils::.DollarNames,%s)", class))
    } else {
      c(sprintf('S3method("$", %s)', class), sprintf("S3method(print, %s)", class),
        sprintf("S3method(utils::.DollarNames, %s)", class))
    }
  }))
}

# The formal arguments of a wrapper, with the defaults of `/// @default`.
.rzig_formals_text <- function(item) {
  arguments <- vapply(item$parameters, function(parameter) {
    default <- item$defaults[parameter]
    text <- .rzig_r_identifier(parameter)
    if (!is.null(item$defaults) && !is.na(default)) paste0(text, " = ", default) else text
  }, character(1L))
  paste(arguments, collapse = ", ")
}

.rzig_doc_lines <- function(doc) {
  if (!nzchar(doc)) return(character())
  lines <- strsplit(doc, "\n", fixed = TRUE)[[1L]]
  if (grepl("\n$", doc)) lines <- c(lines, "")
  lines
}

.rzig_roxygen_block <- function(item) {
  lines <- .rzig_doc_lines(item$doc)
  trimmed <- trimws(lines, whitespace = "[ \t\r]")
  out <- ""
  first_content <- trimmed[nzchar(trimmed)]
  if (!nzchar(item$doc) || (length(first_content) && substring(first_content[[1L]], 1L, 1L) == "@")) {
    out <- paste0(out, "#' Call ", .rzig_r_identifier(item$name), " in Zig.\n")
  }
  if (nzchar(item$doc)) {
    for (line in lines) {
      out <- paste0(out, "#'", if (nzchar(line)) paste0(" ", line) else "", "\n")
    }
  }
  out <- paste0(out, "#'\n")
  if (.rzig_is_internal(item)) {
    # An internal routine is called by the package's own R code; it needs no
    # help page and is not exported.
    return(paste0(out, "#' @keywords internal\n#' @noRd\n"))
  }
  for (parameter in item$parameters) {
    if (.rzig_doc_has_parameter(trimmed, parameter)) next
    out <- paste0(
      out, "#' @param ", .rzig_r_identifier(parameter),
      " A value passed to the Zig implementation.\n"
    )
  }
  constructor <- identical(item$class$role, "constructor")
  if (!.rzig_doc_has_tag(trimmed, "@return")) {
    out <- paste0(out, if (constructor) {
      sprintf("#' @return An object of class `%s`: an external pointer to a Zig value.\n", item$class$name)
    } else {
      "#' @return The value returned by the Zig implementation.\n"
    })
  }
  if (constructor && length(item$class$methods)) {
    out <- paste0(out, "#' @section Methods:\n#' For an object `x` made by `", item$name, "()`:\n")
    for (method in item$class$methods) {
      text <- strsplit(trimws(.rzig_parse_doc(method$doc)$text), "\n[[:space:]]*\n")[[1L]]
      text <- if (length(text) && nzchar(text[[1L]])) gsub("[[:space:]]*\n[[:space:]]*", " ", text[[1L]]) else
        "A method implemented in Zig."
      out <- paste0(out, "#' * `x$", method$name, "(", paste(method$parameters, collapse = ", "), ")`: ", text, "\n")
    }
  }
  paste0(out, "#' @export\n")
}

.rzig_doc_has_tag <- function(trimmed, tag) {
  for (line in trimmed) {
    if (!startsWith(line, tag)) next
    if (nchar(line, type = "bytes") == nchar(tag, type = "bytes") ||
        grepl("^[[:space:]]", substring(line, nchar(tag, type = "bytes") + 1L), useBytes = TRUE)) {
      return(TRUE)
    }
  }
  FALSE
}

.rzig_doc_has_parameter <- function(trimmed, parameter) {
  for (line in trimmed) {
    if (!startsWith(line, "@param")) next
    rest <- substring(line, 7L)
    if (!grepl("^[[:space:]]", rest, useBytes = TRUE)) next
    declared <- sub("^[ \t]+", "", rest, useBytes = TRUE)
    if (.rzig_parameter_matches(declared, parameter)) return(TRUE)
  }
  FALSE
}

.rzig_parameter_matches <- function(declared, parameter) {
  width <- nchar(parameter, type = "bytes")
  if (startsWith(declared, parameter)) {
    rest <- substring(declared, width + 1L)
    if (!nzchar(rest) || grepl("^[[:space:]]", rest, useBytes = TRUE)) return(TRUE)
  }
  if (startsWith(declared, paste0("`", parameter, "`"))) {
    rest <- substring(declared, width + 3L)
    if (!nzchar(rest) || grepl("^[[:space:]]", rest, useBytes = TRUE)) return(TRUE)
  }
  FALSE
}

.rzig_render_namespace <- function(exports, aliases, package) {
  out <- paste0("# Generated by rzig::document(): begin\nuseDynLib(", .rzig_r_string(package))
  for (index in seq_along(exports)) {
    out <- paste0(out, ",\n  ", aliases[[index]], " = ", .rzig_r_string(exports[[index]]$name))
  }
  out <- paste0(out, "\n)\n")
  for (item in exports) {
    if (.rzig_is_internal(item)) next
    out <- paste0(out, "export(", .rzig_r_string(item$name), ")\n")
  }
  for (line in .rzig_class_namespace_lines(exports, roxygen = FALSE)) out <- paste0(out, line, "\n")
  paste0(out, "# Generated by rzig::document(): end\n")
}
