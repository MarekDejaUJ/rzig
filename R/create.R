#' Create a package that uses RZig
#'
#' Creates a new package at `path`: a `DESCRIPTION`, the RZig scaffold of
#' [use_rzig()] with its `hello_zig()` example and help page, and, by default,
#' a testthat suite with one test of `hello_zig()`. The package builds with
#' `R CMD INSTALL` once a supported Zig compiler is available (see
#' [find_zig()]) and passes `R CMD check` as created.
#'
#' The package name is the last component of `path`. The default
#' `DESCRIPTION` fields are placeholders for the title, the description and
#' the author; `fields` replaces or adds fields, for example
#' `fields = list(Title = "Fast Rank Statistics", "Authors@R" =
#' 'person("Ada", "Lovelace", email = "ada@example.org", role = c("aut", "cre"))')`.
#' The license is GPL-3, the license of the framework sources the package
#' contains (another field value is the package author's choice).
#'
#' @param path The directory to create. It must not exist or must be empty.
#' @param fields A named list of `DESCRIPTION` fields that replace or extend
#'   the defaults.
#' @param tests If `TRUE`, add `tests/testthat.R` and a test of `hello_zig()`,
#'   with testthat in `Suggests`.
#' @param ci If `TRUE`, add the GitHub Actions workflow of [use_rzig_ci()].
#'
#' @return The normalized path of the package, invisibly.
#' @examples
#' package_path <- file.path(tempdir(), "zigstats")
#' create_rzig_package(package_path)
#' list.files(package_path, recursive = TRUE)
#' unlink(package_path, recursive = TRUE)
#' @export
create_rzig_package <- function(path, fields = list(), tests = TRUE, ci = FALSE) {
  if (length(path) != 1L || !is.character(path) || is.na(path) || !nzchar(path)) {
    stop("`path` must be one directory path", call. = FALSE)
  }
  if (!is.list(fields) || (length(fields) && (is.null(names(fields)) || any(!nzchar(names(fields)))))) {
    stop("`fields` must be a named list of DESCRIPTION fields", call. = FALSE)
  }
  for (flag in list(tests = tests, ci = ci)) {
    if (length(flag) != 1L || is.na(flag) || !is.logical(flag)) {
      stop("`tests` and `ci` must be TRUE or FALSE", call. = FALSE)
    }
  }
  package <- basename(normalizePath(path, mustWork = FALSE))
  if (!grepl("^[A-Za-z][A-Za-z0-9.]*[A-Za-z0-9]$", package)) {
    stop(sprintf(paste0(
      "`%s` is not a valid package name: use letters, digits and periods, ",
      "starting with a letter and not ending with a period"
    ), package), call. = FALSE)
  }
  if (dir.exists(path) && length(list.files(path, all.files = TRUE, no.. = TRUE))) {
    stop(path, " exists and is not empty; choose a new directory", call. = FALSE)
  }
  if (file.exists(path) && !dir.exists(path)) {
    stop(path, " is a file; choose a new directory", call. = FALSE)
  }
  dir.create(file.path(path, "R"), recursive = TRUE, showWarnings = FALSE)
  path <- normalizePath(path, mustWork = TRUE)

  description <- list(
    Package = package,
    Title = "Functions Written in 'Zig'",
    Version = "0.1.0",
    "Authors@R" = 'person("First", "Last", email = "first.last@example.org", role = c("aut", "cre"))',
    Description = paste(
      "Provides functions written in 'Zig' and called from R through the",
      "native interface generated by 'rzig'."
    ),
    License = "GPL-3",
    Encoding = "UTF-8",
    SystemRequirements = paste("Zig", .rzig_zig_series_label())
  )
  if (tests) {
    description$Suggests <- "testthat (>= 3.0.0)"
    description[["Config/testthat/edition"]] <- "3"
  }
  description[names(fields)] <- lapply(fields, function(value) paste(as.character(value), collapse = " "))
  description$Package <- package
  write.dcf(as.data.frame(description, check.names = FALSE, stringsAsFactors = FALSE),
    file.path(path, "DESCRIPTION"))

  suppressMessages(use_rzig(path))
  if (tests) {
    dir.create(file.path(path, "tests", "testthat"), recursive = TRUE, showWarnings = FALSE)
    .rzig_write_text(paste0(
      "library(testthat)\n", sprintf("library(%s)\n", package), "\n",
      sprintf("test_check(\"%s\")\n", package)
    ), file.path(path, "tests", "testthat.R"))
    .rzig_write_text(paste0(
      "test_that(\"hello_zig greets in Zig\", {\n",
      "  expect_identical(hello_zig(\"R\"), \"Hello, R!\")\n",
      "})\n"
    ), file.path(path, "tests", "testthat", "test-hello-zig.R"))
  }
  if (ci) suppressMessages(use_rzig_ci(path))
  message("Created package ", package, " at ", path, "\n",
    "Write Zig functions in src/rzig/src/main.zig, then run rzig::document(path) ",
    "and rzig::build_zig(path)")
  invisible(path)
}
